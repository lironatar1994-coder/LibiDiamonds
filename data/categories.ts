export const categoryMap: Record<string, Category> = Object.fromEntries(
  categories.map((category) => [category.slug, category]),
);

export function getCategory(slug: string): Category | undefined {
  return categoryMap[slug];
}

/** Categories that appear as jewelry (vs loose stones) */
export const jewelryCategories = categories.filter(
  (c) => c.slug !== "natural-diamonds" && c.slug !== "lab-diamonds",
);

export const diamondCategories = categories.filter(
  (c) => c.slug === "natural-diamonds" || c.slug === "lab-diamonds",
);
